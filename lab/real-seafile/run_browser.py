def find_frame(page, prefix, timeout=60, name=None, parent=None):
    """Seahub posts the token into <iframe name="office_frame">; Playwright may keep reporting
    that frame's URL as about:blank after a form-POST navigation, so match by name/parent too."""
    end = time.time() + timeout
    while time.time() < end:
        for f in page.frames:
            if f.url.startswith(prefix):
                return f
            if name and f.name == name and (parent is None or f.parent_frame == parent):
                return f
            if parent is not None and f.parent_frame == parent and name is None:
                return f
        page.wait_for_timeout(500)
    return None


def wait_for_saved_response(page, captured, timeout=180):
    """Bounded wait for the first successful (HTTP 200, nonempty) /relay/file capture on
    `captured` while pumping Playwright's synchronous event callbacks: sync Playwright only
    dispatches response callbacks inside Playwright calls, so a sleep-only loop over the
    Python list would starve them and never see a response that arrives while Python sleeps.
    Returns the captured body, or None on timeout."""
    end = time.time() + timeout
    while time.time() < end:
        for st, b in list(captured):
            if st == 200 and b:
                return b
        page.wait_for_timeout(1000)
    return None


def track_downloads(context, downloads):
    """Observe downloads on existing pages and popups, before navigation starts."""
    def attach(page):
        page.on("download", lambda download: downloads.append(download))
    context.on("page", attach)
    for page in context.pages:
        attach(page)


def save_and_capture(page, status_fn, timeout=90):
    """Capture the real save request and wait for host confirmation while pumping events."""
    bodies = []
    def capture(request):
        if request.method == "POST" and request.url.endswith("/relay/save"):
            body = request.post_data_buffer
            if body:
                bodies.append(body)
    page.on("request", capture)
    try:
        page.keyboard.press("Control+s")
        end = time.monotonic() + timeout
        while time.monotonic() < end:
            if bodies and (status_fn() or "").strip().lower() in (
                "saved to seafile", "saved (reconciled after a lost response)"
            ):
                return bodies[0], True
            page.wait_for_timeout(min(100, max(0, (end - time.monotonic()) * 1000)))
        return (bodies[0] if bodies else None), False
    finally:
        page.remove_listener("request", capture)


def open_from_seafile_list(page, base, repo_id, name, timeout=30, middle_click=False):
    """Click the actual file-list link; Seahub may open it here or in a new tab."""
    page.goto(f"{base.rstrip('/')}/library/{repo_id}/", wait_until="domcontentloaded")
    previous_pages = set(page.context.pages)
    previous_url = page.url
    link = page.get_by_role("link", name=name, exact=True)
    if middle_click:
        # CE 13.0.28's left-click handler opens an image overlay. A native middle
        # click follows the same file-list anchor in a new tab, without that handler.
        link.click(button="middle", timeout=timeout * 1000)
    else:
        link.click(timeout=timeout * 1000)
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        opened = [p for p in page.context.pages if p not in previous_pages]
        target = opened[-1] if opened else page
        if opened or page.url != previous_url:
            target.wait_for_url(lambda url: url != "about:blank", timeout=timeout * 1000)
            target.wait_for_load_state("domcontentloaded", timeout=timeout * 1000)
            return target
        page.wait_for_timeout(50)
    raise TimeoutError("file-list click did not open an editor page")


def svg_has_rectangle(data, geometry):
    """Check painted SVG geometry, never embedded editor metadata.

    Cached VectorCraft crates/svg/src/export.rs emits rectangle paths as M/L/Z.
    Fail closed on other path commands/transforms rather than guessing their bounds.
    """
    try:
        root = ET.fromstring(data)
        x, y, w, h = (geometry[k] for k in ("x", "y", "width", "height"))
        corners = {(x, y), (x+w, y), (x+w, y+h), (x, y+h)}
        if any(n.tag.rsplit("}", 1)[-1] == "style" for n in root.iter()):
            return False
        def visit(node, fill="black", stroke="none", stroke_width="1", fill_opacity="1", stroke_opacity="1"):
            if not node.tag.startswith("{http://www.w3.org/2000/svg}"):
                return False
            tag = node.tag.rsplit("}", 1)[-1]
            if tag in ("metadata", "defs", "clipPath", "mask", "symbol") or any(
                key in node.attrib for key in ("transform", "style", "class", "filter", "mask", "clip-path")
            ) or node.get("display") == "none" or node.get("visibility") in ("hidden", "collapse") or float(node.get("opacity", "1")) <= 0:
                return False
            fill, stroke = node.get("fill", fill), node.get("stroke", stroke)
            stroke_width = node.get("stroke-width", stroke_width)
            fill_opacity, stroke_opacity = node.get("fill-opacity", fill_opacity), node.get("stroke-opacity", stroke_opacity)
            painted = (fill not in ("none", "transparent") and float(fill_opacity) > 0) or (
                stroke not in ("none", "transparent") and float(stroke_width) > 0 and float(stroke_opacity) > 0)
            if tag == "rect" and painted:
                if all(float(node.get(k, "0")) == geometry[k] for k in geometry):
                    return True
            if tag == "path" and painted:
                d = node.get("d", "")
                tokens = re.findall(r"[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?", d)
                # One closed, four-corner, straight-edged rectangle; no curves or metadata search.
                if tokens and tokens[0] == "M" and tokens[-1] in ("Z", "z"):
                    points, i = [], 0
                    while i < len(tokens)-1:
                        if tokens[i] not in ("M", "L") or i+2 >= len(tokens):
                            break
                        points.append((float(tokens[i+1]), float(tokens[i+2])))
                        i += 3
                    if i == len(tokens)-1 and len(points) == 4 and set(points) == corners and all(
                        a[0] == b[0] or a[1] == b[1] for a, b in zip(points, points[1:]+points[:1])
                    ):
                        return True
            return any(visit(child, fill, stroke, stroke_width, fill_opacity, stroke_opacity) for child in node)
        return root.tag == "{http://www.w3.org/2000/svg}svg" and visit(root)
    except (ET.ParseError, ValueError, TypeError):
        return False


def figcraft_has_frame(data, marker, geometry):
    """Native format v1: format/src/lib.rs DocumentJson flattens doc::Document.

    doc/src/node.rs flattens NodeKind (`type`), with width/height and an optional
    kurbo Affine six-number array. Only a frame attached to a real page counts.
    """
    try:
        with zipfile.ZipFile(BytesIO(data)) as archive:
            doc = json.loads(archive.read("document.json"))
        nodes = doc["nodes"]
        if not isinstance(nodes, dict) or not all(isinstance(n, dict) for n in nodes.values()):
            return False
        return doc["format"] == "figcraft" and doc["version"] == 1 and any(
            n.get("type") == "frame" and n.get("name") == marker and
            n.get("width") == geometry["width"] and n.get("height") == geometry["height"] and
            n.get("transform", [1, 0, 0, 1, 0, 0]) == [1, 0, 0, 1, geometry["x"], geometry["y"]] and
            n.get("parent") in doc["pages"] and
            nodes[str(n["parent"])].get("type") == "page" and
            n["id"] in nodes[str(n["parent"])].get("children", [])
            for n in nodes.values()
        )
    except (KeyError, TypeError, ValueError, zipfile.BadZipFile):
        return False


